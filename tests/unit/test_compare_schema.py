import importlib.util
import pathlib

SCRIPT = pathlib.Path(__file__).parents[2] / "scripts" / "upgrade-check" / "compare_schema.py"
spec = importlib.util.spec_from_file_location("compare_schema", SCRIPT)
compare_schema = importlib.util.module_from_spec(spec)
spec.loader.exec_module(compare_schema)

BASE = """
-- Dumped from database version 15.4
\\restrict AbC123
SET statement_timeout = 0;
CREATE TABLE public.attachment (
    id integer NOT NULL,
    object_id integer
);
CREATE INDEX attachments_attachment_object_id_idx ON public.attachment USING btree (object_id);
"""


def test_renamed_index_is_reported_but_not_a_problem():
    new = BASE.replace("attachments_attachment_object_id_idx", "attachments_content_44d952_idx").replace("AbC123", "ZzZ999")

    problems, renames = compare_schema.compare(BASE, new)

    assert problems == []
    assert renames == [("attachments_attachment_object_id_idx", "attachments_content_44d952_idx")]


def test_dropped_index_is_a_problem():
    new = "\n".join(l for l in BASE.splitlines() if not l.startswith("CREATE INDEX"))

    problems, _ = compare_schema.compare(BASE, new)

    assert any("CREATE INDEX" in p for p in problems)


def test_changed_column_is_a_problem():
    new = BASE.replace("object_id integer\n", "object_id bigint\n")

    problems, _ = compare_schema.compare(BASE, new)

    assert any("object_id" in p for p in problems)


SERIAL = """
CREATE TABLE public.t (
    id integer NOT NULL
);
CREATE SEQUENCE public.t_id_seq AS integer START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1;
ALTER SEQUENCE public.t_id_seq OWNED BY public.t.id;
ALTER TABLE ONLY public.t ALTER COLUMN id SET DEFAULT nextval('public.t_id_seq'::regclass);
CREATE INDEX t_idx ON public.t USING btree (id);
"""
IDENTITY = """
CREATE TABLE public.t (
    id integer NOT NULL
);
ALTER TABLE public.t ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.t_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
);
CREATE INDEX t_idx ON public.t USING btree (id);
"""


def test_serial_versus_identity_is_a_problem_by_default():
    problems, _ = compare_schema.compare(SERIAL, IDENTITY)

    assert problems


def test_fresh_mode_accepts_serial_versus_identity_but_still_flags_a_dropped_index():
    problems, _ = compare_schema.compare(SERIAL, IDENTITY, fresh=True)
    assert problems == []

    problems, _ = compare_schema.compare(SERIAL, IDENTITY.replace("CREATE INDEX t_idx ON public.t USING btree (id);", ""), fresh=True)
    assert any("CREATE INDEX" in p for p in problems)


def test_fresh_mode_accepts_the_history_historyentry_not_null_difference():
    old = "CREATE TABLE public.history_historyentry (\n    type smallint\n);\n"
    new = "CREATE TABLE public.history_historyentry (\n    type smallint NOT NULL\n);\n"

    assert compare_schema.compare(old, new)[0]
    assert compare_schema.compare(old, new, fresh=True)[0] == []


def test_fresh_mode_ignores_per_project_reference_sequences_of_sample_data():
    old = "CREATE SEQUENCE public.references_project7 START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1;\n"

    assert compare_schema.compare(old, "")[0]
    assert compare_schema.compare(old, "", fresh=True)[0] == []
